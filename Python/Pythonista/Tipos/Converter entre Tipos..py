# Conversão de Tipos
idade = input (' Qual e sua idade ? :')
print(int(idade) > 18) # converteu "str" para "int"

print(type(str(5))) # converteu "int" para "str"

# Receber valores decimais 
altura_da_parede = input("Qual e altura da parede : ")
print(float(altura_da_parede) > 2.10)

