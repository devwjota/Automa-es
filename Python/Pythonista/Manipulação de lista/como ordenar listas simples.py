valores =[31,23,6,36,38,40,22]
valores.sort() #metodo 'sort' para ordernar listas obs:ordem crescente
print(valores)

valores =[31,23,6,36,38,40,22]
valores.sort(reverse=True) #metodo 'reverse=True' para ordernar listas obs:ordem decrescente
print(valores)

# Inverter uma Lista
valores.reverse() #valores que estavam no final foram pro começo 'variavel.reverse()'
print(valores)



